// Demo: several agents attempt the SAME task in parallel, each on its own branch of agents-demo-full
// (attempt/<name>), so git.next can compare the attempts and pick one to merge.
//
// Each attempt: sliced context with the org catalog pinned (POST /context, which also reports other work touching the
// same files) → one model call through the git-next AI Gateway, tagged with the shared task id → edits on a local
// clone → commit with Agent / Agent-Task trailers → push to refs/heads/attempt/<name> with a short-lived write token
// (GIT_CONFIG_* env vars only). No new repos: branches of the existing project. Pushes to agents-demo-full raise
// Artifacts push events, so the deployed Worker analyses each branch too.
// Afterwards it asks the local Worker to compare the attempts and writes samples/attempts-demo.json.
//
// Needs the local Worker (`npm run dev`) and .dev.vars with CF_ACCOUNT_ID + AIG_LOGS_TOKEN.
// Usage: node scripts/demo-attempts.ts [--worker-url http://localhost:5173] [--budget-usd 10] [--only attempt-sonnet,…] [--keep] [--compare-only]
import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { applyEdits, estimateUsd, gatewaySpend, parseEdits, workerPost } from "./agent-lib.ts";

const ROOT = resolve(dirname(new URL(import.meta.url).pathname), "..");
const PROJECT = "agents-demo-full";
const GATEWAY_ID = "git-next";
const TASK_ID = "feature#uploads-ai";
const TASK = "Add a small server-only Worker example that stores uploaded files in R2 and returns a one-line AI-generated description of each upload";
const PATHS = ["examples/uploads-ai/src/index.ts", "examples/uploads-ai/wrangler.jsonc"];
const INCLUDE = ["examples/mcp-server/package.json", "examples/mcp-server/wrangler.jsonc", "examples/mcp-server/tsconfig.json", "examples/mcp-server/src/index.ts"];
const INSTRUCTIONS =
	"Create a minimal server-only example in examples/uploads-ai/ (package.json, wrangler.jsonc, tsconfig.json, README.md, src/index.ts), modelled on the examples/mcp-server files shown. PUT /files/:key stores the request body in an R2 bucket; GET /files/:key returns it with a one-line description generated by a Workers AI model. Choose the bucket, binding and model yourself. Keep every file short.";

/** The attempts: same task, same context, different models. */
const ATTEMPTS = [
	{ name: "attempt-sonnet", model: "anthropic/claude-sonnet-5.5", maxTokens: 3000 },
	{ name: "attempt-haiku", model: "anthropic/claude-haiku-4.5", maxTokens: 3000 },
	{ name: "attempt-glm", model: "@cf/zai-org/glm-5.3-flash", maxTokens: 3000 },
];

const argv = process.argv.slice(2);
const opt = (name: string, fallback?: string) => {
	const i = argv.indexOf(name);
	return i >= 0 ? argv[i + 1] : fallback;
};
const WORKER = opt("--worker-url", "http://localhost:5173")!;
const BUDGET_USD = Number(opt("--budget-usd", "10"));
const ONLY = opt("--only")?.split(",");
const KEEP = argv.includes("--keep");
const COMPARE_ONLY = argv.includes("--compare-only");
const WORKDIR = join(tmpdir(), "git-next-demo-attempts");

const post = <T>(path: string, body: unknown) => workerPost<T>(WORKER, path, body);
const git = (cwd: string, ...args: string[]) => execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
/** Git with an Authorization header supplied only through GIT_CONFIG_* env vars (never argv, config or URLs). */
const gitWithToken = (cwd: string, args: string[], token: string) =>
	spawnSync("git", args, { cwd, encoding: "utf8", env: { ...process.env, GIT_CONFIG_COUNT: "1", GIT_CONFIG_KEY_0: "http.extraHeader", GIT_CONFIG_VALUE_0: `Authorization: Bearer ${token}`, GIT_TERMINAL_PROMPT: "0" } });
const redact = (s: string) => s.replace(/Bearer\s+\S+/g, "Bearer ***").replace(/https:\/\/[0-9a-f]{32}\.artifacts\.cloudflare\.net/g, "https://<account>.artifacts.cloudflare.net").replaceAll(WORKDIR, "<workdir>");
const branchOf = (name: string) => `attempt/${name.replace(/^attempt-/, "")}`;

async function runAttempt(a: (typeof ATTEMPTS)[number], budget: { remaining: number }) {
	const say = (s: string) => console.log(`[${a.name}] ${s}`);
	const dir = join(WORKDIR, a.name);
	const read = await post<{ token: string; remote: string }>("/dev/token", { repo: PROJECT, scope: "read", ttl: 600 });
	const clone = gitWithToken(WORKDIR, ["clone", "-q", "--single-branch", "--branch", "main", read.remote, dir], read.token);
	if (clone.status !== 0) throw new Error(`clone failed: ${redact(clone.stderr)}`);

	const ctx = await post<any>("/context", { repo: PROJECT, ref: "main", task: TASK, paths: PATHS, budgetTokens: 3000, layers: "demo", catalog: "org" });
	say(`context: ${ctx.stats.tokensServed} tokens, ${ctx.rules.length} rules, ${ctx.pinned?.relevant?.length ?? 0} catalog entries pinned`);
	for (const o of ctx.inFlight ?? []) say(`in flight: ${o.repo}${o.ref !== "main" ? `@${o.ref}` : ""} (${o.agent ?? "?"}) touches ${[...o.same, ...o.near].slice(0, 3).join(", ")}`);

	const files = INCLUDE.map((p) => `--- ${p} ---\n${readFileSync(join(dir, p), "utf8")}`).join("\n\n");
	const rules = ctx.rules.map((r: any) => `- ${r.topic}: ${r.value}${r.strength === "must" ? " (must)" : ""} [${r.kind}]`).join("\n");
	const pinned = [ctx.pinned?.catalog, ...(ctx.pinned?.relevant ?? [])].filter(Boolean).join("\n");
	const system =
		'You are a careful coding agent working in the cloudflare/agents repo. Reply with ONLY a JSON object: {"summary": "<imperative, under 60 chars>", "edits": [{"path", "content"}]}. Create new files with content. No prose outside the JSON.';
	const prompt = `Task: ${TASK}\n\n${INSTRUCTIONS}\n\nOrg catalog (approved models, resources, gateway):\n${pinned}\n\nResolved rules:\n${rules}\n\nFiles:\n${files}`;
	const estimate = estimateUsd(a.model, system.length + prompt.length, a.maxTokens);
	if (estimate > budget.remaining) throw new Error(`budget: estimated $${estimate.toFixed(3)} exceeds remaining $${budget.remaining.toFixed(3)}`);
	budget.remaining -= estimate;

	const llm = await post<{ text: string; usage: any }>("/dev/llm", { model: a.model, system, prompt, maxTokens: a.maxTokens, metadata: { developer: "chris", repo: PROJECT, fork: PROJECT, agent: a.name, task: TASK_ID } });
	say(`model ${a.model}: ${JSON.stringify(llm.usage)}`);
	const plan = parseEdits(llm.text);
	const edits = applyEdits(dir, plan.edits, (p) => p.startsWith("examples/uploads-ai/"));
	git(dir, "add", "-A");
	execFileSync("git", ["-c", `user.name=${a.name}`, "-c", `user.email=${a.name}@git-next.local`, "commit", "-q", "-m", `SOW-1042: ${plan.summary.replace(/^sow-\d+:\s*/i, "")}`, "-m", `Agent: ${a.name} (${a.model}) via git.next\nAgent-Task: ${TASK_ID}`], { cwd: dir });
	const head = git(dir, "rev-parse", "HEAD");
	const write = await post<{ token: string }>("/dev/token", { repo: PROJECT, scope: "write", ttl: 600 });
	const push = gitWithToken(dir, ["push", "-q", "--force", "origin", `HEAD:refs/heads/${branchOf(a.name)}`], write.token);
	if (push.status !== 0) throw new Error(`push failed: ${redact(push.stderr)}`);
	say(`pushed ${head.slice(0, 10)} to ${PROJECT}@${branchOf(a.name)} (${edits.length} files): ${plan.summary}`);
	return { attempt: a.name, model: a.model, branch: branchOf(a.name), head, summary: plan.summary, files: edits.map((e) => e.path), usage: llm.usage, inFlight: ctx.inFlight ?? [] };
}

const attempts = ATTEMPTS.filter((a) => !ONLY || ONLY.includes(a.name));
const runs: Record<string, unknown>[] = [];
if (!COMPARE_ONLY) {
	rmSync(WORKDIR, { recursive: true, force: true });
	mkdirSync(WORKDIR, { recursive: true });
	const before = await gatewaySpend(ROOT, GATEWAY_ID);
	const budget = { remaining: BUDGET_USD - before };
	console.log(`gateway spend before: $${before.toFixed(6)} (budget $${BUDGET_USD})`);
	if (budget.remaining <= 0) throw new Error("budget already spent");
	const settled = await Promise.allSettled(attempts.map((a) => runAttempt(a, budget)));
	settled.forEach((s, i) => runs.push(s.status === "fulfilled" ? s.value : { attempt: attempts[i].name, model: attempts[i].model, error: redact(String(s.reason)) }));
	for (const r of runs) if (r.error) console.log(`[${r.attempt}] FAILED: ${r.error}`);
}

// Compare: gateway logs can lag a few seconds, so retry until every attempt has its spend recorded (or ~60 s).
const refs = ATTEMPTS.map((a) => branchOf(a.name)).join(",");
let comparison: any = null;
for (let i = 0; i < 20; i++) {
	const res = await fetch(`${WORKER}/work/compare?${new URLSearchParams({ repo: PROJECT, task: TASK_ID, refs })}`);
	comparison = await res.json();
	if (comparison.error || comparison.attempts.every((x: any) => x.cost.requests > 0)) break;
	await new Promise((r) => setTimeout(r, 3000));
}
if (comparison.error) throw new Error(`compare: ${comparison.error}`);
const after = await gatewaySpend(ROOT, GATEWAY_ID);
writeFileSync(join(ROOT, "samples/attempts-demo.json"), `${redact(JSON.stringify({ generatedAt: new Date().toISOString(), generatedBy: "scripts/demo-attempts.ts", task: TASK, runs, ...comparison }, null, 2))}\n`);
console.log(`\ngateway total $${after.toFixed(6)}`);
for (const r of comparison.attempts) console.log(`#${r.rank} ${(r.agent ?? r.ref).padEnd(15)} ${r.verdict.padEnd(8)} ${r.reasons.join("; ")}`);
if (!KEEP) rmSync(WORKDIR, { recursive: true, force: true });
if (runs.some((r) => r.error)) process.exitCode = 1;
